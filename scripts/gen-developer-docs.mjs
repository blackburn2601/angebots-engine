// Build-time generator: turns docs/developer/*.md into a bundled TS module.
//
// Why bundle instead of reading at runtime? next.config.mjs uses
// `output: "standalone"`, and the Dockerfile only copies the standalone
// server + .next/static — the docs/ folder is NOT present at runtime in
// production. Compiling the content into a TS module guarantees it ships
// inside the server bundle.
//
// Re-run automatically via the `predev` / `prebuild` npm hooks, or manually:
//   node scripts/gen-developer-docs.mjs

import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { marked } from "marked";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const SRC_DIR = join(ROOT, "docs", "developer");
const OUT_FILE = join(ROOT, "src", "generated", "developer-docs.ts");

// README becomes the "overview" entry and is shown first; the rest follow in
// filename order (01-…, 02-…, …).
function slugFor(fileName) {
  const base = fileName.replace(/\.md$/i, "");
  return base.toLowerCase() === "readme" ? "overview" : base;
}

function titleFor(markdown, fileName) {
  const heading = markdown.match(/^#\s+(.+?)\s*$/m);
  if (heading) return heading[1].replace(/\s*[—–-]\s*Developer Documentation$/i, "").trim();
  return fileName.replace(/\.md$/i, "");
}

// Rewrite cross-document links (./04-database.md, 04-database.md#seeding, …)
// into in-page anchors (#04-database) so navigation works on the single
// stacked-sections page.
function rewriteLinks(html) {
  return html.replace(
    /href="(?:\.\/)?([\w-]+)\.md(?:#[\w-]+)?"/gi,
    (_match, base) => `href="#${slugFor(`${base}.md`)}"`
  );
}

const files = readdirSync(SRC_DIR)
  .filter((f) => f.toLowerCase().endsWith(".md"))
  .sort((a, b) => {
    const rank = (f) => (f.toLowerCase() === "readme.md" ? "" : f); // README first
    return rank(a).localeCompare(rank(b));
  });

const docs = files.map((fileName) => {
  const markdown = readFileSync(join(SRC_DIR, fileName), "utf8");
  const html = rewriteLinks(marked.parse(markdown, { async: false, gfm: true }));
  return { slug: slugFor(fileName), title: titleFor(markdown, fileName), html };
});

const banner =
  "// AUTO-GENERATED by scripts/gen-developer-docs.mjs — do not edit by hand.\n" +
  "// Source: docs/developer/*.md. Regenerated on predev/prebuild.\n\n";

const body =
  "export interface DeveloperDoc {\n" +
  "  slug: string;\n" +
  "  title: string;\n" +
  "  html: string;\n" +
  "}\n\n" +
  `export const developerDocs: DeveloperDoc[] = ${JSON.stringify(docs, null, 2)};\n`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, banner + body, "utf8");

console.log(`Generated ${OUT_FILE} from ${docs.length} developer docs.`);
